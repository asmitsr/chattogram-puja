// থানা/উপজেলা → এলাকার তালিকা (সমতল)
export const CTG_FLAT: Record<string, string[]> = Object.assign({}, ...CTG_GROUPS.map((g) => g.places));

export function isValidPlace(thana: string, locality: string): boolean {
  const list = CTG_FLAT[thana];
  if (!list) return false;
  return locality === OTHER_AREA || list.includes(locality);
}

// ---- অঞ্চল: মহানগর / উত্তর চট্টগ্রাম / দক্ষিণ চট্টগ্রাম ----
// অ্যাডমিন তালিকার ফিল্টারে ব্যবহার হয়। বিন্যাস বদলাতে চাইলে শুধু নিচের দুটি তালিকা বদলান।
export type RegionKey = 'metro' | 'north' | 'south' | 'other';
export const REGION_LABEL: Record<RegionKey, string> = {
  metro: 'মহানগর',
  north: 'উত্তর চট্টগ্রাম',
  south: 'দক্ষিণ চট্টগ্রাম',
  other: 'অন্যান্য',
};
const NORTH_UPAZILAS = ['হাটহাজারী', 'ফটিকছড়ি', 'রাউজান', 'রাঙ্গুনিয়া', 'সীতাকুণ্ড', 'মীরসরাই'];
const SOUTH_UPAZILAS = ['বোয়ালখালী', 'পটিয়া', 'চন্দনাইশ', 'সাতকানিয়া', 'লোহাগাড়া', 'বাঁশখালী', 'আনোয়ারা', 'সন্দ্বীপ'];
const METRO_THANAS = Object.keys(CTG_GROUPS[0]?.places ?? {});

// এলাকার লেখা (যেমন "মেট্রোপলিটন এলাকা (মহানগর)", "দক্ষিণ চট্টগ্রাম", "জ্যেষ্ঠপুরা, শ্রীপুর-খরন্দ্বীপ, বোয়ালখালী, চট্টগ্রাম") থেকে অঞ্চল চেনা
export function regionOf(area: string | null | undefined): RegionKey {
  const a = (area ?? '').normalize('NFC');
  if (!a) return 'other';
  // v57 ধাঁচ: "অঞ্চল · থানা · এলাকা" — শুরুর শব্দেই অঞ্চল চেনা যায়
  if (a.startsWith('মহানগর')) return 'metro';
  if (a.startsWith('উত্তর চট্টগ্রাম')) return 'north';
  if (a.startsWith('দক্ষিণ চট্টগ্রাম')) return 'south';
  if (a.includes('মেট্রোপলিটন') || a.includes('মহানগর')) return 'metro';
  if (a.includes('উত্তর চট্টগ্রাম')) return 'north';
  if (a.includes('দক্ষিণ চট্টগ্রাম')) return 'south';
  // ফর্মে থানা বেছে জমা দিলে এলাকা "এলাকা, থানা, চট্টগ্রাম" আকারে থাকে
  const parts = a.split(',').map((s) => s.trim());
  for (const part of parts) {
    if (NORTH_UPAZILAS.includes(part)) return 'north';
    if (SOUTH_UPAZILAS.includes(part)) return 'south';
  }
  for (const part of parts) if (METRO_THANAS.includes(part)) return 'metro';
  return 'other';
}

// ---- v57: তালিকা অঞ্চল ও থানা অনুযায়ী ভাগ ----
export const REGION_ORDER: RegionKey[] = ['metro', 'north', 'south', 'other'];
export const AREA_SEP = ' · ';
const REGION_WORDS = ['মহানগর', 'উত্তর চট্টগ্রাম', 'দক্ষিণ চট্টগ্রাম'];

// "মহানগর · কোতোয়ালী · পাথরঘাটা" → অঞ্চল, থানা (উত্তর/দক্ষিণে উপজেলা), এলাকা।
// পুরনো ধাঁচের লেখায় (যেমন "উত্তর চট্টগ্রাম") থানা/এলাকা থাকে না: thana ও locality null।
export function splitArea(area: string | null | undefined): {
  region: RegionKey;
  thana: string | null;
  locality: string | null;
  rest: string;
} {
  const a = (area ?? '').normalize('NFC').trim();
  const region = regionOf(a);
  const parts = a
    .split(AREA_SEP)
    .map((x) => x.trim())
    .filter(Boolean);
  if (parts.length > 0 && REGION_WORDS.includes(parts[0])) {
    return { region, thana: parts[1] ?? null, locality: parts[2] ?? null, rest: parts.slice(1).join(AREA_SEP) };
  }
  return { region, thana: null, locality: null, rest: a };
}
